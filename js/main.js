/* ── Render Project Cards ── */
function renderProjects() {
  const grid = document.getElementById('projects-grid');
  if (!grid) return;

  templates.forEach(t => {
    const card = document.createElement('a');
    card.className = 'project-card';
    card.href = t.link;
    card.target = '_blank';
    card.rel = 'noopener';
    card.innerHTML = `
      <div class="project-img">
        <img src="${t.screenshot}" alt="${t.name} template preview" loading="lazy" />
      </div>
      <div class="project-body">
        <h3 class="project-title">${t.name}</h3>
        <p class="project-desc">${t.description}</p>
      </div>
    `;
    grid.appendChild(card);
  });
}

renderProjects();


/* ── Spotlight Border Effect ── */
function initSpotlightCards() {
  const cards = document.querySelectorAll('.project-card');
  cards.forEach(card => {
    card.addEventListener('pointermove', (e) => {
      const rect = card.getBoundingClientRect();
      const x = e.clientX - rect.left;
      const y = e.clientY - rect.top;
      card.style.setProperty('--card-x', x + 'px');
      card.style.setProperty('--card-y', y + 'px');
    });
  });
}
initSpotlightCards();

/* ── GSAP + ScrollTrigger Setup ── */
gsap.registerPlugin(ScrollTrigger);

/* ── Character Reveal Animation ── */
function charReveal(selector) {
  document.querySelectorAll(selector).forEach(el => {
    const split = new SplitType(el, { types: 'words, chars' });

    gsap.from(split.chars, {
      opacity: 0,
      y: 18,
      scale: 1.45,
      filter: 'blur(10px)',
      duration: 0.8,
      ease: 'power4.out',
      stagger: 0.03,
      scrollTrigger: {
        trigger: el,
        start: 'top 85%',
        once: true
      }
    });
  });
}

/* ── Fade Up Animation ── */
function fadeUp(selector) {
  document.querySelectorAll(selector).forEach(el => {
    gsap.from(el, {
      opacity: 0,
      y: 40,
      filter: 'blur(6px)',
      duration: 0.8,
      ease: 'power3.out',
      scrollTrigger: {
        trigger: el,
        start: 'top 88%',
        once: true
      }
    });
  });
}

/* ── Card Stagger Animation ── */
function staggerCards(selector) {
  document.querySelectorAll(selector).forEach(grid => {
    const cards = grid.children;
    gsap.from(cards, {
      opacity: 0,
      y: 80,
      duration: 0.7,
      ease: 'power3.out',
      stagger: 0.15,
      scrollTrigger: {
        trigger: grid,
        start: 'top 85%',
        once: true
      }
    });
  });
}

/* ── Counter Animation ── */
function animateCounters() {
  document.querySelectorAll('[data-count]').forEach(el => {
    const target = parseInt(el.dataset.count, 10);

    gsap.fromTo(el,
      { innerText: 0 },
      {
        innerText: target,
        duration: 2,
        ease: 'power2.out',
        snap: { innerText: 1 },
        scrollTrigger: {
          trigger: el,
          start: 'top 90%',
          once: true
        }
      }
    );
  });
}

/* ── Initialize All Animations ── */
function initAnimations() {
  // Character reveals
  charReveal('.hero-title, .section-heading, .cta-heading');

  // Fade ups
  fadeUp('.hero-label, .hero-sub, .hero-ctas, .hero-badges, .section-label, .contact-sub, .contact-form');

  // Card staggers (exclude projects grid — animate each card individually for alignment)
  staggerCards('.features-grid, .services-grid, .process-grid');

  // Projects grid: fade each card on its own scroll trigger so rows stay level
  document.querySelectorAll('.projects-grid .project-card').forEach(card => {
    gsap.from(card, {
      opacity: 0,
      y: 40,
      duration: 0.6,
      ease: 'power3.out',
      scrollTrigger: {
        trigger: card,
        start: 'top 90%',
        once: true
      }
    });
  });

  // Counters
  animateCounters();
}

// Wait for fonts + SplitType to be ready
document.fonts.ready.then(() => {
  initAnimations();
});

/* ── Navbar Scroll Behavior ── */
(function () {
  const navbar = document.querySelector('.navbar');
  if (!navbar) return;

  window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 50);
  }, { passive: true });
})();

/* ── Smooth Scroll for Anchor Links ── */
(function () {
  document.querySelectorAll('a[href^="#"]').forEach(link => {
    link.addEventListener('click', e => {
      const target = document.querySelector(link.getAttribute('href'));
      if (!target) return;
      e.preventDefault();

      // Close mobile menu if open
      const mobileMenu = document.querySelector('.mobile-menu');
      const hamburger = document.querySelector('.hamburger');
      if (mobileMenu && mobileMenu.classList.contains('open')) {
        mobileMenu.classList.remove('open');
        hamburger.classList.remove('active');
        hamburger.setAttribute('aria-expanded', 'false');
        document.body.style.overflow = '';
      }

      target.scrollIntoView({ behavior: 'smooth' });
    });
  });
})();

/* ── Hamburger Menu Toggle ── */
(function () {
  const hamburger = document.querySelector('.hamburger');
  const mobileMenu = document.querySelector('.mobile-menu');
  if (!hamburger || !mobileMenu) return;

  hamburger.addEventListener('click', () => {
    const isOpen = mobileMenu.classList.toggle('open');
    hamburger.classList.toggle('active');
    hamburger.setAttribute('aria-expanded', String(isOpen));
    document.body.style.overflow = isOpen ? 'hidden' : '';
  });
})();

/* ── Contact Form Submission (Web3Forms) ── */
(function () {
  const form = document.getElementById('contact-form');
  const success = document.getElementById('form-success');
  if (!form || !success) return;

  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const btn = form.querySelector('.form-submit');
    btn.classList.add('loading');
    btn.disabled = true;

    try {
      const res = await fetch(form.action, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json', 'Accept': 'application/json' },
        body: JSON.stringify(Object.fromEntries(new FormData(form)))
      });
      const data = await res.json();

      if (data.success) {
        form.hidden = true;
        success.hidden = false;
      } else {
        alert('Something went wrong. Please try again or email us at contact@nextgenlab.studio');
      }
    } catch {
      alert('Something went wrong. Please try again or email us at contact@nextgenlab.studio');
    } finally {
      btn.classList.remove('loading');
      btn.disabled = false;
    }
  });
})();
